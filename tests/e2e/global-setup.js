import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { PDFDocument, StandardFonts, rgb } from 'pdf-lib'
import { gradientPng, noisePng } from './helpers/png.js'

const here = path.dirname(fileURLToPath(import.meta.url))
const fixtures = path.join(here, 'fixtures')

function write(name, data) {
  fs.writeFileSync(path.join(fixtures, name), data)
}

async function textPdf(paths, title) {
  const pdf = await PDFDocument.create()
  const font = await pdf.embedFont(StandardFonts.Helvetica)
  for (const [index, label] of paths.entries()) {
    const page = pdf.addPage([595.28, 841.89])
    page.drawText(`${title} - page ${index + 1}`, { x: 60, y: 760, size: 22, font, color: rgb(0.1, 0.1, 0.1) })
    page.drawText('Generated by Filevra test fixtures. This page exists only for local testing.', {
      x: 60,
      y: 720,
      size: 11,
      font,
      color: rgb(0.3, 0.3, 0.3),
    })
    page.drawText(label, { x: 60, y: 690, size: 14, font, color: rgb(0.15, 0.35, 0.75) })
  }
  return Buffer.from(await pdf.save())
}

async function imagePdf(png) {
  const pdf = await PDFDocument.create()
  const image = await pdf.embedPng(png)
  const page = pdf.addPage([595.28, 841.89])
  page.drawImage(image, { x: 0, y: 0, width: 595.28, height: 595.28 })
  return Buffer.from(await pdf.save())
}

export default async function globalSetup() {
  fs.mkdirSync(fixtures, { recursive: true })
  write('noise.png', noisePng(900, 700))
  write('gradient.png', gradientPng(1200, 800))
  write('doc-a.pdf', await textPdf(['alpha', 'beta'], 'Filevra fixture A'))
  write('doc-b.pdf', await textPdf(['gamma'], 'Filevra fixture B'))
  write('heavy.pdf', await imagePdf(gradientPng(1500, 1500)))
}
