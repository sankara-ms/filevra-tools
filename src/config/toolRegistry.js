export const TOOLS = [...CUSTOM_TOOLS, ...PDF_TOOLS, ...IMAGE_TOOLS, ...DOCUMENT_TOOLS, ...SHEET_TOOLS, ...PRESENTATION_TOOLS, ...TEXT_TOOLS, ...FILE_TOOLS]

export const TOOL_BY_ID = Object.fromEntries(TOOLS.map((tool) => [tool.id, tool]))
export const TOOL_BY_PATH = Object.fromEntries(TOOLS.map((tool) => [tool.path, tool]))
export const POPULAR_TOOLS = TOOLS.filter((tool) => tool.popular)
export const GENERIC_TOOLS = TOOLS.filter((tool) => !tool.custom)

export function getToolByPath(path) {
  return TOOL_BY_PATH[path] || null
}

export function getCategoryTools(categoryId) {
  return TOOLS.filter((tool) => tool.category === categoryId)
}

export function getRelatedTools(currentId, count = 3) {
  const current = TOOL_BY_ID[currentId]
  if (!current) return TOOLS.slice(0, count)
  const same = TOOLS.filter((tool) => tool.id !== currentId && tool.category === current.category)
  const other = TOOLS.filter((tool) => tool.id !== currentId && tool.category !== current.category)
  return [...same, ...other].slice(0, count)
}

export function searchTools(query) {
  const normalized = String(query || '').trim().toLowerCase()
  if (!normalized) return TOOLS
  return TOOLS.filter((tool) =>
    [tool.name, tool.description, CATEGORY_BY_ID[tool.category]?.name, ...(tool.keywords || [])]
      .join(' ')
      .toLowerCase()
      .includes(normalized),
  )
}

